import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";

// Import supplied artwork only. Originals are immutable; registry aliases reuse XML.
const source = path.resolve(process.argv[2] || "assets/provided/muni-componentes-v1");
const destination = "assets/provided/muni-componentes-v1";
const catalogue = JSON.parse(fs.readFileSync(path.join(source, "catalogo.json"), "utf8"));
const mapping = JSON.parse(fs.readFileSync(path.join(source, "mapa-integracion.json"), "utf8"));
const hash = bytes => crypto.createHash("sha256").update(bytes).digest("hex");
const manifest = JSON.parse(fs.readFileSync("assets/manifest.json", "utf8"));
const art = {}, aliases = {}, states = {};

function preserve(from, to) {
  const bytes = fs.readFileSync(from);
  if (fs.existsSync(to)) {
    if (hash(fs.readFileSync(to)) !== hash(bytes)) throw new Error(`Existing original differs: ${to}`);
  } else {
    fs.mkdirSync(path.dirname(to), { recursive: true });
    fs.writeFileSync(to, bytes);
  }
  return bytes;
}
for (const name of ["catalogo.json", "mapa-integracion.json"])
  preserve(path.join(source, name), `${destination}/${name}`);

for (const asset of catalogue) {
  const localPath = `${destination}/${asset.svg}`;
  const bytes = preserve(path.join(source, asset.svg), localPath);
  const original = bytes.toString("utf8");
  if (hash(bytes) !== asset.sha256) throw new Error(`Catalogue hash differs: ${asset.id}`);
  if (/<(?:image|script|foreignObject)\b/i.test(original)) throw new Error(`Unsupported content: ${asset.id}`);
  const viewBox = original.match(/viewBox="([^"]+)"/)?.[1].trim().split(/[ ,]+/).map(Number);
  if (!viewBox || viewBox.length !== 4 || viewBox.some(n => !Number.isFinite(n))) throw new Error(`Invalid viewBox: ${asset.id}`);
  const ids = new Map([...original.matchAll(/\bid="([^"]+)"/g)].map((m, i) => [m[1], `muni3-${asset.id}-${i}`]));
  let xml = original.replace(/<\?xml[^>]*>/g, "").replace(/<!DOCTYPE[^>]*>/g, "")
    .replace(/\bid="([^"]+)"/g, (_, id) => `id="${ids.get(id)}"`)
    .replace(/url\(#([^)]*)\)/g, (_, id) => `url(#${ids.get(id) || id})`)
    .replace(/((?:xlink:)?href=")#([^"]+)"/g, (_, prefix, id) => `${prefix}#${ids.get(id) || id}"`);
  const derivedPath = `assets/derived/muni-componentes-v1/${asset.id}.svg`;
  fs.mkdirSync(path.dirname(derivedPath), { recursive: true });
  fs.writeFileSync(derivedPath, xml);
  // Only the bridge has intentional surrounding whitespace. Keep its SVG viewBox;
  // the renderer fits the documented visible bounds inside its layout box.
  let frame;
  if (asset.id === "world-2-puente") {
    const [x,y,w,h] = asset.contentBoundsPng;
    frame = [(x-6)/1400, (y-6)/933, (w+12)/1400, (h+12)/933];
  }
  const ratio = frame ? viewBox[2]*frame[2]/(viewBox[3]*frame[3]) : viewBox[2]/viewBox[3];
  art[asset.id] = { xml, aspectRatio: ratio, ...(frame ? { frame } : {}) };
  const id = `componentes-v1/${asset.id}`;
  const existing = manifest.assets.find(a => a.id === id);
  const entry = { id, assetId: asset.id, kind: "supplied-vector", status: "integrated-local", localPath, derivedPath,
    sha256: hash(bytes), derivedSha256: hash(xml), viewBox: viewBox.join(" "), rasterEmbedded: false,
    source: existing?.source || { kind: "local-user-delivery", path: `muni-componentes-v1/${asset.svg}`, package: "muni-componentes-v1" },
    figmaNodeId: existing?.figmaNodeId || null, figmaStatus: existing?.figmaNodeId ? "mapped" : "pending-access",
    transformation: "Removed XML/DOCTYPE headers and prefixed internal IDs; original geometry, viewBox, fills and transparency retained.",
    ...(frame ? { displayFrame: frame, frameNote: "Catalogue bridge bounds plus 6 px padding; trims only transparent margin in the view, not in the SVG." } : {}) };
  const index = manifest.assets.findIndex(a => a.id === id);
  if (index < 0) manifest.assets.push(entry); else manifest.assets[index] = entry;
}
for (const [slot, target] of Object.entries(mapping.slots)) {
  if (!art[target.assetId]) throw new Error(`Unknown asset for ${slot}`);
  if (target.registry === "characterStates") states[slot] = target.assetId;
  else aliases[slot] = target.assetId;
}
const module = `// Generated by scripts/import-illustrations.mjs from supplied local originals.\n` +
  `export type IllustrationAsset = { xml: string; aspectRatio: number; frame?: number[] };\n` +
  `export const providedIllustrations: Record<string, IllustrationAsset> = ${JSON.stringify(art)};\n` +
  `export const illustrationAliases: Record<string,string> = ${JSON.stringify(aliases, null, 2)};\n` +
  `export const characterAssetIds: Record<string,string> = ${JSON.stringify(states)};\n` +
  `export const illustrationData: Record<string,IllustrationAsset> = { ...providedIllustrations, ...Object.fromEntries(Object.entries(illustrationAliases).map(([slot,id])=>[slot,providedIllustrations[id]])) };\n` +
  `export const illustrationAssets: Record<string,string> = Object.fromEntries(Object.entries(illustrationData).map(([id,asset])=>[id,asset.xml]));\n`;
fs.writeFileSync("src/design/illustration-assets.ts", module);
manifest.version = 3;
manifest.status = "brand-originals-and-local-component-pack-integrated";
manifest.missing = "All 91 revision-02 slots covered by the supplied SVG package. Figma nodes for the 95 new assets remain pending access; no new Figma download is claimed.";
const pendingFigmaNodes = catalogue.filter(a => !manifest.assets.find(entry => entry.id === `componentes-v1/${a.id}`)?.figmaNodeId).map(a => ({assetId: a.id, nodeId: null}));
manifest.componentIntegration = { package: "muni-componentes-v1", catalogue: `${destination}/catalogo.json`, mapping: `${destination}/mapa-integracion.json`, uniqueAssets: catalogue.length, slots: Object.keys(mapping.slots).length, extras: mapping.extras, pendingFigmaNodes };
fs.writeFileSync("assets/manifest.json", JSON.stringify(manifest, null, 2)+"\n");
const pending = JSON.parse(fs.readFileSync("assets/pending-revision-02.json", "utf8"));
pending.status = "all-slots-integrated-from-local-delivery";
pending.placeholder = "Historical X placeholders replaced with supplied SVGs in revision 03.";
pending.integratedSlots = Object.keys(mapping.slots);
pending.remainingIllustrations = [];
pending.instructions = "The IDs above are retained as the revision-02 inventory. All are covered by assets/provided/muni-componentes-v1/mapa-integracion.json. Figma node association remains pending; artwork is integrated from the local delivery.";
fs.writeFileSync("assets/pending-revision-02.json", JSON.stringify(pending, null, 2)+"\n");
console.log(`Integrated ${catalogue.length} unique SVGs, ${Object.keys(mapping.slots).length} exact slots, ${mapping.extras.length} extra assets. No original overwritten.`);
